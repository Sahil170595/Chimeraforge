# Vendor and product line, which the engine-support gate needs: SGLang and TGI
# document ROCm on Instinct only, TGI on Intel covers Data Center GPU Max only.
# Derived from the vendor's own product naming by one rule rather than typed per
# entry, and validated against a closed vocabulary.
PRODUCT_LINES = {
    "nvidia": {"geforce", "rtx-pro", "datacenter", "dgx-spark"},
    "amd": {"instinct", "radeon", "ryzen-ai-max"},
    "intel": {"arc-pro", "datacenter-max"},
    "apple": {"apple-silicon"},
}
# Product lines whose CPU and GPU share one memory pool.
UNIFIED_LINES = {"apple-silicon", "ryzen-ai-max", "dgx-spark"}


def vendor_line(name: str) -> tuple[str, str]:
    """(vendor, product_line) from a database name; raises on anything unknown."""
    if name.startswith("Apple "):
        return "apple", "apple-silicon"
    if name.startswith("Ryzen AI Max"):
        return "amd", "ryzen-ai-max"
    if name.startswith("DGX Spark"):
        return "nvidia", "dgx-spark"
    if name.startswith("RTX PRO "):
        return "nvidia", "rtx-pro"
    if name.startswith("RTX "):
        return "nvidia", "geforce"
    if name.split()[0] in {"A100", "H100", "H200", "B200", "L4", "T4"}:
        return "nvidia", "datacenter"
    if name.startswith("MI"):
        return "amd", "instinct"
    if name.startswith(("RX ", "Radeon ")):
        return "amd", "radeon"
    if name.startswith("Arc Pro "):
        return "intel", "arc-pro"
    raise ValidationError(f"{name}: no vendor/product-line rule matches this name")


# Sanity bounds. Anything outside these is far more likely to be a typo or a
# unit mix-up than a real part, so it fails the build rather than shipping.
BOUNDS = {
    "vram_gb": (1.0, 1024.0),
    "bandwidth_gbps": (10.0, 50000.0),
    "cost_per_hour": (0.001, 100.0),
    "fp16_tflops": (1.0, 100000.0),
    "tdp_watts": (5.0, 3000.0),
    "interconnect_gbps": (1.0, 10000.0),
}


class ValidationError(Exception):
    """The dataset does not satisfy the schema or its sanity bounds."""


def _iso(value: str, where: str) -> None:
    try:
        dt.date.fromisoformat(value)
    except (TypeError, ValueError) as exc:
        raise ValidationError(f"{where}: captured_at {value!r} is not an ISO date") from exc


def validate(data: dict) -> list[str]:
    """Raise on anything unshippable; return non-fatal notes."""
    if data.get("schema_version") != SCHEMA_VERSION:
        raise ValidationError(f"unsupported schema_version: {data.get('schema_version')!r}")
    _iso(data.get("captured_at", ""), "top level")
    gpus = data.get("gpus")
    if not isinstance(gpus, list) or not gpus:
        raise ValidationError("no gpus in dataset")

    notes: list[str] = []
    seen: set[str] = set()
    for entry in gpus:
        name = entry.get("name", "<unnamed>")
        for key in REQUIRED:
            if key not in entry:
                raise ValidationError(f"{name}: missing {key!r}")
        if name in seen:
            raise ValidationError(f"duplicate GPU name {name!r}")
        seen.add(name)
        if not str(entry["source_url"]).startswith("https://"):
            raise ValidationError(f"{name}: source_url must be https")
        _iso(entry["captured_at"], name)
        if entry["price_basis"] not in PRICE_BASES:
            raise ValidationError(
                f"{name}: price_basis {entry['price_basis']!r} not one of {sorted(PRICE_BASES)}"
            )
        if entry["tflops_basis"] not in TFLOPS_BASES:
            raise ValidationError(
                f"{name}: tflops_basis {entry['tflops_basis']!r} not one of {sorted(TFLOPS_BASES)}"
            )
        for field, (lo, hi) in BOUNDS.items():
            value = entry[field]
            if value is None:
                # A null is legal and means "no vendor source". It disables the
                # prediction that depends on it rather than defaulting.
                notes.append(f"{name}: {field} is null -- dependent predictions are unknown")
                continue
            if not isinstance(value, (int, float)):
                raise ValidationError(f"{name}: {field} is not a number")
            if not lo <= value <= hi:
                raise ValidationError(f"{name}: {field}={value} outside [{lo}, {hi}]")
        if entry["product_line"] not in PRODUCT_LINES.get(entry["vendor"], set()):
            raise ValidationError(
                f"{name}: vendor/product_line {entry['vendor']}/{entry['product_line']} "
                "not in the vocabulary"
            )
        if entry["unified_memory"] != (entry["product_line"] in UNIFIED_LINES):
            raise ValidationError(f"{name}: unified_memory disagrees with its product line")
        options = entry["memory_options_gb"]
        if entry["unified_memory"]:
            # vram_gb is the largest configuration; every configuration is listed.
            if not options or max(options) != entry["vram_gb"]:
                raise ValidationError(f"{name}: memory_options_gb must list sizes up to vram_gb")
        elif options is not None:
            raise ValidationError(f"{name}: memory_options_gb is for unified-memory devices")
        if not isinstance(entry["fp8_supported"], bool):
            raise ValidationError(f"{name}: fp8_supported must be a bool")
        # A null TFLOPS figure must say why, and a reason-for-null must not sit
        # beside a number -- otherwise an unlabeled headline could ship as dense.
        if (entry["fp16_tflops"] is None) != (entry["tflops_basis"] in TFLOPS_NULL_BASES):
            raise ValidationError(
                f"{name}: fp16_tflops={entry['fp16_tflops']!r} does not agree with "
                f"tflops_basis={entry['tflops_basis']!r}"
            )
        for field, url in (entry.get("field_sources") or {}).items():
            if field not in REQUIRED:
                raise ValidationError(f"{name}: field_sources names unknown field {field!r}")
            if not str(url).startswith("https://"):
                raise ValidationError(f"{name}: field_sources[{field}] must be https")
    return notes


def _with_identity(entry: dict) -> dict:
    vendor, line = vendor_line(entry["name"])
    return {
        **entry,
        "vendor": vendor,
        "product_line": line,
        "unified_memory": line in UNIFIED_LINES,
        "memory_options_gb": entry.get("memory_options_gb"),
    }


def build() -> dict:
    return {
        "schema_version": SCHEMA_VERSION,
        "captured_at": max(g["captured_at"] for g in GPUS),
        "note": (
            "GPU specifications with per-entry source and capture date. Values are "
            "vendor-published figures; `tflops_basis` records which column each "
            "TFLOPS number came from, since a with-sparsity headline halved is not "
            "a datasheet row. `price_basis` distinguishes an amortised purchase "
            "price from a rental rate -- the two are not the same quantity, and "
            "the field drives the budget gate and the self-host-vs-API break-even. "
            "A null field means no vendor source; it disables the prediction that "
            "depends on it rather than defaulting. Regenerate with "
            "scripts/build_hardware_data.py."
        ),
        "gpus": [_with_identity(g) for g in GPUS],
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="validate the bundled dataset")
    ap.add_argument("--write", action="store_true", help="regenerate the bundled dataset")
    args = ap.parse_args()

    if args.write:
        data = build()
        validate(data)
        DATASET.parent.mkdir(parents=True, exist_ok=True)
        DATASET.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {DATASET} ({len(data['gpus'])} GPUs)")
        return 0

    if not DATASET.exists():
        print(f"dataset missing: {DATASET}", file=sys.stderr)
        return 1
    data = json.loads(DATASET.read_text(encoding="utf-8"))
    notes = validate(data)
    for note in notes:
        print(f"  note: {note}")
    print(f"OK: {len(data['gpus'])} GPUs, captured {data['captured_at']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
