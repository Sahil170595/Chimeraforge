def _load_constants():
    """constants.py by file path, NOT through the package: importing
    chimeraforge.planner loads hardware.json, so a schema change could never be
    regenerated by the script that regenerates it. constants.py imports nothing."""
    import importlib.util

    path = ROOT / "src" / "chimeraforge" / "planner" / "constants.py"
    spec = importlib.util.spec_from_file_location("_chimeraforge_constants", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


