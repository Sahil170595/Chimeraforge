# -- Unified-memory devices (P8.6 item 4) --------------------------------------
# CPU and GPU share one pool, so `vram_gb` is the LARGEST configuration sold and
# `memory_options_gb` lists every configuration; a plan uses the share the user
# states (--unified-memory-fraction), and --hardware auto uses the detected size.
# Read 2026-09-26 from Apple's current Mac spec pages / newsroom (the M4 iMac and
# the A18 Pro MacBook Neo are still sold), AMD's Ryzen AI Halo pages and NVIDIA's
# DGX Spark docs; M5 Max and M5 Ultra bandwidth and AMD's FP16 line re-read
# against the live pages. Deliberately null, per the dataset's rules:
#   - Apple publishes no GPU TFLOPS, and no chip power (only whole-system figures).
#   - AMD's "60 FP16 TFLOPS" is unlabeled dense/sparse, so it is not used.
#   - NVIDIA publishes only "1 PFLOP FP4" with sparsity for DGX Spark, no FP16.
#   - Prices: Apple sells configured Macs, not chips, so a chip price would be one
#     configuration's; the DGX Spark price is not on an NVIDIA page.
#   - M5 Ultra 512 GB is announced but not orderable ("coming late October").
#   - Interconnect: single devices; tensor parallelism across them is not modelled.
_UNI = "2026-09-26"
APPLE = "https://www.apple.com/"
AMD_HALO = (
    "https://www.amd.com/en/products/processors/desktops/ryzen/ryzen-ai-halo/"
    "ryzen-ai-max-plus-395.html"
)
NV_SPARK = "https://docs.nvidia.com/dgx/dgx-spark/hardware.html"


def _unified(
    name,
    memory,
    bandwidth,
    source,
    *,
    tdp=None,
    tflops_basis=TFLOPS_UNPUBLISHED,
    field_sources=None,
    **extra,
):
    return dict(
        name=name,
        vram_gb=float(max(memory)),
        memory_options_gb=[float(m) for m in memory],
        bandwidth_gbps=float(bandwidth),
        cost_per_hour=None,
        price_basis=BASIS_AMORTISED,
        fp16_tflops=None,
        tflops_basis=tflops_basis,
        tdp_watts=tdp,
        interconnect_gbps=None,
        fp8_supported=False,  # no vendor states FP8 matrix support for these
        source_url=source,
        captured_at=_UNI,
        **({"field_sources": field_sources} if field_sources else {}),
        **extra,
    )


